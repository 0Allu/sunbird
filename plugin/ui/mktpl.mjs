// Extracts Phoenix's own Settings layouts from captured UI-op batches (build 356207) into
// plugin/runtime/src/settings_tpl.js. Text is scrubbed (the page capture is a real account page).
// usage: node mktpl.mjs uiops.js settings.hex accountPage.hex out.js
import { readFileSync, writeFileSync } from 'node:fs';
const [, , uiops, settingsCap, pageCap, out] = process.argv;
new Function(readFileSync(uiops, 'utf8'))();

const load = (f) => {
  const ops = PhxUI.decode(Uint8Array.from(Buffer.from(readFileSync(f, 'utf8').trim(), 'hex')));
  const create = new Map(), kids = new Map();
  for (const o of ops) { if (o.op === 'create') create.set(o.id, o); if (o.op === 'children') kids.set(o.id, o.ids); }
  const strip = (props) => props.filter((p) => p.k !== 'worklet')
    .map((p) => ({ k: p.k, v: JSON.parse(JSON.stringify(p.v, (k, v) => (typeof v === 'bigint' ? String(v) : v))) }))
    .map((p) => (['text', 'accessibilityLabel', 'value'].includes(p.k) ? { k: p.k, v: { t: 'str', v: '' } } : p));
  const tree = (id) => ({ type: create.get(id).type, props: strip(create.get(id).props), kids: (kids.get(id) || []).map(tree), src: id });
  return { create, tree, strip };
};
const clean = (n) => { delete n.src; n.kids.forEach(clean); return n; };
const find = (n, id) => (n.src === id ? n : n.kids.map((k) => find(k, id)).find(Boolean));

const s = load(settingsCap), p = load(pageCap);
const leaf = (t, id) => ({ ...t.tree(id), kids: [] });

// page: root > ... > [spacer, line, scroll > content(sections go here), floating header > back + title]
const page = p.tree(0x4de);
find(page, 0x4e4).kids = [];
const T = {
  section: clean(leaf(s, 0x411)), header: clean(leaf(s, 0x412)), group: clean(leaf(s, 0x413)),
  switchRow: clean(s.tree(0x46f)), trackOff: s.strip(s.create.get(0x4a2).props), knobOff: s.strip(s.create.get(0x4a3).props),
  divider: clean(s.tree(0x41a)), buttonRow: clean(s.tree(0x42b)),
  valueRow: clean(p.tree(0x544)), // label ... value > chevron
  input: clean(s.tree(0x336)), // Settings search: row > box > [icon wrap > icon, input]
  page, // ids to address: spacer 0x4e1, content 0x4e4, header 0x562, back button 0x565, title 0x56a (kept as `src`)
};
const keep = (n) => { if (![0x4e1, 0x4e4, 0x562, 0x565, 0x56a].includes(n.src)) delete n.src; n.kids.forEach(keep); };
keep(T.page);
writeFileSync(out, "// Generated by plugin/ui/mktpl.mjs from captured Settings batches (356207): Phoenix's own layouts.\nglobalThis.__phx_tpl = " + JSON.stringify(T) + ';\n');
console.log('ok', JSON.stringify(T).length, 'bytes');
